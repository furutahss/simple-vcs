import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";
import { chooseVersion, shouldMakeLatest, setVersion, checkVersions, prepareRelease } from "./release.mjs";

function git(root, ...args) {
  return execFileSync("git", ["-c", "user.name=Release test", "-c", "user.email=release@example.invalid", "-c", "commit.gpgsign=false", ...args], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}
function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "simple-vcs-release-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, "src-tauri"));
  writeFileSync(join(root, "package.json"), JSON.stringify({ name: "simple-vcs", version: "1.0.0" }, null, 2) + "\n");
  writeFileSync(join(root, "package-lock.json"), JSON.stringify({ name: "simple-vcs", version: "1.0.0", packages: { "": { name: "simple-vcs", version: "1.0.0" }, "node_modules/example": { version: "1.0.0" } } }, null, 2) + "\n");
  writeFileSync(join(root, "Cargo.toml"), '[workspace]\nmembers = []\n\n[workspace.package]\nversion = "1.0.0"\nedition = "2021"\n');
  writeFileSync(join(root, "Cargo.lock"), '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "simple-vcs"\nversion = "1.0.0"\n\n[[package]]\nname = "vcs-core"\nversion = "1.0.0"\n\n[[package]]\nname = "external"\nversion = "1.0.0"\nsource = "registry+https://example.invalid"\n');
  writeFileSync(join(root, "src-tauri/tauri.conf.json"), '{"version":"../package.json"}\n');
  git(root, "init", "-b", "main");
  git(root, "add", "."); git(root, "commit", "-m", "initial source");
  return root;
}

test("初版、patch増分、桁上り、明示major/minorを採番する", () => {
  assert.equal(chooseVersion("1.0.0", []), "1.0.0");
  assert.equal(chooseVersion("1.0.0", ["1.0.0"]), "1.0.1");
  assert.equal(chooseVersion("1.0.0", ["1.0.9", "1.0.2"]), "1.0.10");
  assert.equal(chooseVersion("1.1.0", ["1.0.9"]), "1.1.0");
  assert.equal(chooseVersion("2.0.0", ["1.9.9"]), "2.0.0");
});

test("不正なバージョンや0.xへの初版指定を拒否する", () => {
  for (const version of ["01.0.0", "1.0", "v1.0.0", "1.0.0-beta", "0.9.0", "1.0.9007199254740992"]) {
    assert.throws(() => chooseVersion(version, []));
  }
});

test("古い下書きの再実行では公開済みの最新版を巻き戻さない", () => {
  assert.equal(shouldMakeLatest("1.0.0", []), true);
  assert.equal(shouldMakeLatest("1.0.10", ["1.0.9", "1.0.2"]), true);
  assert.equal(shouldMakeLatest("1.0.0", ["1.0.1"]), false);
  assert.equal(shouldMakeLatest("1.9.9", ["2.0.0"]), false);
});

test("配布物の検査は中間.appを除外し、欠けたインストーラーを拒否する", t => {
  const root = mkdtempSync(join(tmpdir(), "simple-vcs-assets-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const workflow = readFileSync(new URL("../.github/workflows/release.yml", import.meta.url), "utf8");
  const step = workflow.split("- name: Verify installer set and generate checksums\n")[1].split("      - name:")[0];
  const script = step.split("        run: |\n")[1].replace(/^          /gm, "");
  const names = ["app.exe", "app.msi", "app.deb", "app.AppImage", "app_aarch64.dmg", "app_x64.dmg"];
  for (const name of names) writeFileSync(join(root, name), "installer fixture");
  mkdirSync(join(root, "Simple VCS.app"));
  for (const name of ["win-portable.zip", "mac-arm-portable.zip", "mac-intel-portable.zip", "linux-portable.zip"]) writeFileSync(join(root, name), "portable fixture");
  execFileSync("bash", ["-e", "-c", script], { cwd: root, stdio: "pipe" });
  const checksums = readFileSync(join(root, "SHA256SUMS"), "utf8").trim().split("\n");
  assert.equal(checksums.length, 10);
  assert.ok(checksums.every(line => !line.includes(".app")));
  rmSync(join(root, "app_x64.dmg"));
  assert.throws(() => execFileSync("bash", ["-e", "-c", script], { cwd: root, stdio: "pipe" }));
});

test("アプリ版だけ同期し、依存バージョンを変えない", t => {
  const root = fixture(t);
  setVersion(root, "1.2.3");
  assert.equal(JSON.parse(readFileSync(join(root, "package.json"))).version, "1.2.3");
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json")));
  assert.equal(lock.version, "1.2.3"); assert.equal(lock.packages[""].version, "1.2.3");
  assert.equal(lock.packages["node_modules/example"].version, "1.0.0");
  assert.match(readFileSync(join(root, "Cargo.toml"), "utf8"), /version = "1.2.3"/);
  assert.match(readFileSync(join(root, "Cargo.lock"), "utf8"), /name = "vcs-core"\nversion = "1.2.3"/);
  assert.match(readFileSync(join(root, "Cargo.lock"), "utf8"), /name = "external"\nversion = "1.0.0"/);
  assert.equal(checkVersions(root), "1.2.3");
  lock.version = "1.2.2"; writeFileSync(join(root, "package-lock.json"), JSON.stringify(lock));
  assert.throws(() => checkVersions(root));
});

test("Windowsの改行でも版の検査と更新ができる", t => {
  const root = fixture(t);
  for (const path of ["Cargo.toml", "Cargo.lock"]) writeFileSync(join(root, path), readFileSync(join(root, path), "utf8").replaceAll("\n", "\r\n"));
  assert.equal(checkVersions(root), "1.0.0");
  setVersion(root, "1.0.1");
  assert.equal(checkVersions(root), "1.0.1");
});

test("初版タグと再実行は同じ版・同じソースを使用する", t => {
  const root = fixture(t); const source = git(root, "rev-parse", "HEAD");
  const first = prepareRelease(root, source);
  assert.equal(first.tag, "v1.0.0"); assert.equal(first.skip, false);
  assert.equal(git(root, "rev-parse", "v1.0.0^{commit}"), first.commit);
  git(root, "checkout", "--detach", source);
  assert.deepEqual(prepareRelease(root, source), first);
  assert.equal(git(root, "tag", "--list"), "v1.0.0");
});

test("次のpushはpatchを増やし、mainを進めずタグに採番ソースを保存する", t => {
  const root = fixture(t); const initial = git(root, "rev-parse", "HEAD");
  prepareRelease(root, initial);
  git(root, "checkout", "main");
  writeFileSync(join(root, "change.txt"), "change"); git(root, "add", "change.txt"); git(root, "commit", "-m", "small change");
  const source = git(root, "rev-parse", "HEAD"); git(root, "checkout", "--detach", source);
  const next = prepareRelease(root, source);
  assert.equal(next.tag, "v1.0.1");
  assert.equal(git(root, "rev-parse", "main"), source);
  assert.equal(JSON.parse(git(root, "show", "v1.0.1:package.json")).version, "1.0.1");
  assert.equal(git(root, "rev-parse", `${next.commit}^`), source);
  git(root, "checkout", "--detach", source);
  assert.deepEqual(prepareRelease(root, source), next);
});

test("後のpushに含まれた古いイベントでReleaseを巻き戻さない", t => {
  const root = fixture(t); const old = git(root, "rev-parse", "HEAD");
  writeFileSync(join(root, "change.txt"), "new source"); git(root, "add", "."); git(root, "commit", "-m", "newer source");
  const newer = git(root, "rev-parse", "HEAD"); prepareRelease(root, newer);
  git(root, "checkout", "--detach", old);
  assert.equal(prepareRelease(root, old).skip, true);
  assert.equal(git(root, "tag", "--list"), "v1.0.0");
});

test("別HEADや未保存の変更があれば採番前に拒否する", t => {
  const root = fixture(t); const source = git(root, "rev-parse", "HEAD");
  assert.throws(() => prepareRelease(root, "0".repeat(40)));
  writeFileSync(join(root, "package.json"), '{"version":"9.0.0"}\n');
  assert.throws(() => prepareRelease(root, source));
  assert.equal(git(root, "tag", "--list"), "");
});
